-- Q.8  Calculate the total sale value (sale_price) generated by each city.

SELECT 
    buyer_city, SUM(sale_price) AS Total_Sales
FROM
    property_bookings
GROUP BY buyer_city
ORDER BY Total_Sales DESC;

-- Q.9 Find the top 5 buyers by total amount spent across all their bookings.
SELECT 
    buyer_id,
    buyer_name,
    buyer_city,
    SUM(sale_price) AS Total_spent
FROM
    property_bookings
GROUP BY buyer_id , buyer_name , buyer_city
ORDER BY Total_spent DESC
LIMIT 5;

