 -- Q.18 Using a CTE and ROW_NUMBER(), find the top-performing agent (by total sale value) in each city.
 
 WITH top_performer_by_city AS (SELECT agent_name,city,SUM(sale_price) AS total_sale FROM property_bookings b
INNER JOIN properties p ON p.property_id = b.property_id
GROUP BY agent_name,city),
ranking_agents AS (
SELECT agent_name,city,total_sale,ROW_NUMBER()OVER(PARTITION BY city ORDER BY total_sale DESC )
AS rrank_number FROM top_performer_by_city)
SELECT agent_name,city,total_sale FROM ranking_agents
WHERE rrank_number = 1;

-- Q.19 Calculate the running (cumulative) monthly sale value across 2024-2025 using a window function.

WITH monthly_sales AS
 (SELECT YEAR(booking_date) AS sale_year,MONTH(booking_date) AS sale_month,
 SUM(sale_price) monthly_total FROM properties p
INNER JOIN property_bookings b ON p.property_id = b.property_id
GROUP BY sale_year,sale_month
ORDER BY sale_year,sale_month)
SELECT sale_year,sale_month,monthly_total,SUM(monthly_total)OVER
(ORDER BY sale_year,sale_month)AS  running_total FROM monthly_sales
ORDER BY  sale_year,sale_month
;

