-- Q.21 Calculate year-over-year (YoY) growth percentage in total sale value for each city using LAG()

WITH yearly_city_sales AS 
(SELECT city,YEAR(booking_date) AS sales_year,sum(sale_price) 
AS current_year_sales FROM properties p 
INNER JOIN property_bookings b ON p.property_id = b.property_id
GROUP BY city,YEAR(booking_date)),
sales_with_previous_year AS (
SELECT city,sales_year,current_year_sales,LAG(current_year_sales) 
OVER(PARTITION BY city ORDER BY sales_year)
AS previous_year_sales FROM yearly_city_sales)
SELECT city,sales_year,current_year_sales,previous_year_sales,
ROUND((current_year_sales - previous_year_sales)*100.00/( previous_year_sales),2)
 AS Growth_pct FROM sales_with_previous_year
ORDER BY city,sales_year;

-- Q.22 -- Segment buyers into 'Premium', 'Mid' and 'Budget' tiers based on total spend using CASE combined with aggregation, then count buyers per tier. 

with buyer_spent as (select buyer_name,sum(sale_price) as total_spent from properties p inner join property_bookings b on p.property_id = b.property_id
group by buyer_name),
category_count as (select 
  case when total_spent <=50000000 then "Budget"
 when total_spent between 100000000 and 200000000 then "Mid"
 when total_spent between  20000001 and 5000000000 then "Preimium" end as Price_category
 from buyer_spent)
select Price_category,count(Price_category) AS count_of_category from category_count
group by Price_category;

